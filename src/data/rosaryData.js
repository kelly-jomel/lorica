export function getTodayMystery() {
  const dayOfWeek = new Date().getDay(); // 0 = Sun, 1 = Mon, ..., 6 = Sat
  switch (dayOfWeek) {
    case 1: // Monday
    case 6: // Saturday
      return ROSARY_MYSTERIES.joyful;
    case 2: // Tuesday
    case 5: // Friday
      return ROSARY_MYSTERIES.sorrowful;
    case 4: // Thursday
      return ROSARY_MYSTERIES.luminous;
    case 0: // Sunday
    case 3: // Wednesday
    default:
      return ROSARY_MYSTERIES.glorious;
  }
}
